def write_weapon_defs(defs_directory):
    source = ET.parse(defs_directory / 'SpaceCombat/DeltaV_SpaceWeapons.xml').getroot()
    result = ET.Element('Defs')
    result.append(ET.Comment(' Generated by scripts/TutorialContent/build.py for WeaponRange. '))
    for name, original in WEAPON_SOURCES.items():
        definition = deepcopy(source.find(f"ThingDef[defName='{original}']"))
        definition.find('defName').text = name
        category = definition.find('designationCategory')
        if category is None:
            category = ET.SubElement(definition, 'designationCategory')
        category.clear()
        category.set('IsNull', 'True')
        if name == RANGE_RAPID:
            definition.find('label').text = 'range medium rapid turret'
            definition.find("comps/li[@Class='DeltaV.CompProperties_WeaponTuning']/maxMass").text = '10'
            description = definition.find('description')
            if description is None:
                description = ET.SubElement(definition, 'description')
            description.text = 'A medium rapid turret calibrated for ten heads per shot at the weapons range.'
        else:
            definition.find('label').text = 'range railgun loading unit'
            definition.find("comps/li[@Class='DeltaV.CompProperties_SpaceWeaponMagazine']/ammoPerShot").text = '45'
            definition.find('description').text = definition.findtext('description').replace('30 uranium', '45 uranium', 1)
        result.append(definition)
    ET.indent(result)
    text = ET.tostring(result, encoding='utf-8', xml_declaration=True) + b'\n'
    destination = defs_directory / 'Tutorial/DeltaV_TutorialRangeWeapons.xml'
    if not destination.exists() or destination.read_bytes() != text:
        destination.write_bytes(text)


def shape(name):
    size = (44, 28) if name == 'WeaponRange' else (31, 44)
    arrow = ({(x,2) for x in range(1,6)} | {(4,1),(4,3)}) if name == 'WeaponRange' else set()
    return dict(size=size, cells={(x,z) for x in range(size[0]) for z in range(size[1])},
                surfaceDefs={c:'GoldTile' for c in arrow})


def furnish(name, plan, place, prop, foundation, roofs, records, occupied):
    magazine_slots = []
    if name == 'WeaponRange':
        # The sealed cabin occupies the south of the rectangular deck.
        walls = {(x,z) for x in range(44) for z in range(17) if x in (0,43) or z in (0,16)}
        walls |= {(6,z) for z in range(1,6)} | {(x,5) for x in range(1,6)}
        walls -= {(0,2),(6,2),(33,16)}
        for x,z in sorted(walls): place('GravshipHull',x,z)
        place('DeltaV_DockingPort',0,2,3)
        place('DeltaV_RangeBlastDoor',6,2,1)
        place('Door',33,16)
        roofs.intersection_update({(x,z) for x in range(44) for z in range(17)})
        place('DeltaV_RangeTerminal_Introduction',4,4,2)
        for x,presets in TERMINAL_COLUMNS:
            for z,preset in zip(TERMINAL_ROWS,presets):
                place('DeltaV_RangeTerminal_'+preset,x,z,2)
        place('PilotConsole',38,10)
        place('OxygenPump',2,4)
        place('OxygenPump',9,15)
        place('Heater',34,8)
        place('StandingLamp',33,11)
        for x in (40,42): place('Bed',x,1)
        for x in range(10,40,2):
            for z in (1,3,5,7): place('Battery',x,z,1)
        for x in (8,9):
            for z in range(1,9): place('GravcorePowerCell',x,z)
        place('DeltaV_ShieldGenerator',34,12,state={'DeltaV_shieldGroundRadius':'40'})
        families = (RANGE_RAPID, 'DeltaV_Weapon_HeavyMainMedium', 'DeltaV_Weapon_LaserMainMedium')
        for group,(weapon,x) in enumerate(zip(families,(8,16,24)),1):
            for secondary,z in ((False,23),(True,19)):
                settings={'groupNumber':str(group),'salvoSet':'Secondary' if secondary else 'Main'}
                if group==1: settings.update(firingInterval='10',headUnits='10')
                elif group==2: settings.update(propellantCharge='48',headUnits='48')
                else: settings.update(pulsePower='3')
                if group in (1,2):
                    settings['_selectedHead'] = URANIUM_HEAD if secondary else STEEL_HEAD
                gun=place(weapon,x,z,1,state=settings)
                slots="comps/li[@Class='DeltaV.CompProperties_SpaceWeapon']/attachmentSlots"
                def east_slot(index):
                    sx,_,sz=map(int,re.findall(r'-?\d+',prop(weapon,f'{slots}/li[{index}]/cell')))
                    return gun['root'][0]+sz,gun['root'][1]-sx
                place('DeltaV_Building_AutoAimPluginII',*east_slot(1),1,layer='attachment')
                if group in (1,2):
                    magazine_slots.append((east_slot(2),settings['_selectedHead']))
        loader=place(RANGE_RAIL,34,21,1,state={'groupNumber':'4','salvoSet':'Secondary'})
        for x in range(35,44): place('DeltaV_Weapon_RailgunAccelerator',x,21,1)
        assert loader['root'][1] == 22
        start=(1,2)
    else:
        roofs.clear()
        walls={(x,z) for x in range(6) for z in range(44)}
        paint_by_row={z:paint for rows,paint,_ in TARGET_BANDS for z in rows}
        for x,z in sorted(walls):
            state={'paintColorDef':paint_by_row[z]} if x==0 else None
            place('Wall',x,z,stuff='Steel',state=state)
        for x in (11,15):
            for z in range(2,42): place('Wall',x,z,stuff='Steel')
        off={'switchOn':'False','wantSwitchOn':'False'}
        for x,z,radius,angle in ((6,7,18,-45),(21,34,39,0),(18,12,14,None)):
            place('DeltaV_ShieldGenerator',x,z,3,state={**off,'DeltaV_shieldGroundRadius':str(radius),
                'DeltaV_shieldProjection':'32','DeltaV_shieldLength':'32',
                'DeltaV_shieldAngle':str(angle or 0),'_rangeLine':angle is not None})
        place('PilotConsole',25,9)
        place('Battery',28,13)
        for x in (8,12,16,20,24): place('Battery',x,30,state={'storedPower':'0'})
        for z in range(16,20): place('GravcorePowerCell',22,z)
        start=(26,8)
    transmit={tuple(c) for r in records if r['name'] in ('Battery','GravcorePowerCell') for c in r['cells']}
    # Empty target batteries stay isolated from the live grid.
    isolated={(x+dx,z+dz) for r in records if name=='ShieldTarget' and r['name']=='Battery'
              and r['stateOverrides'].get('storedPower')=='0' for x,z in r['cells']
              for dx,dz in ((0,0),(1,0),(-1,0),(0,1),(0,-1))}
    for x,z in sorted(foundation-transmit-isolated): place('HiddenConduit',x,z,layer='conduit')
    for slot,head in magazine_slots:
        place(MAGAZINE,*slot,1,layer='attachment',state={'_selectedHead':head})
    return walls,start


def prepare_state(r, state, field, prop):
    name=r['name']
    if name == 'PilotConsole':
        combat=state.find('combat')
        if combat is None: combat=ET.SubElement(state,'combat')
        field(combat,'fireControlMode','Disabled')
    if name == 'Wall':
        base=float(prop(name,'statBases/MaxHitPoints','100'))
        factor=float(prop(r['stuff'],'stuffProps/statFactors/MaxHitPoints','1'))
        offset=float(prop(r['stuff'],'stuffProps/statOffsets/MaxHitPoints','0'))
        field(state,'health',round(base*factor+offset))
    is_weapon = name.startswith('DeltaV_Weapon_') and 'Accelerator' not in name
    if is_weapon:
        for obsolete in ('fuel','configuredTargetFuelLevel','allowAutoRefuel','lastMagazineThingId'):
            node=state.find(obsolete)
            if node is not None: state.remove(node)
    if is_weapon or name == MAGAZINE:
        selected_head=r['stateOverrides'].get('_selectedHead')
        for kind,tag in [('Heads','headSupply'),('Propellant','propellantSupply')]:
            capacity=prop(name,"comps/li[@Class='DeltaV.CompProperties_GunSupply'][kind='"+kind+"']/fuelCapacity")
            if capacity:
                node=ET.SubElement(state,tag)
                field(node,'fuel',capacity)
                field(node,'configuredTargetFuelLevel',capacity)
                field(node,'allowAutoRefuel','True')
                if kind == 'Heads' and selected_head:
                    field(node,'selectedHead',selected_head)
    if is_weapon:
        if name != RANGE_RAIL:
            coverage=ET.SubElement(state,'combatCoverage')
            field(coverage,'arc','90')
            field(coverage,'range','150')
            field(state,'manualFireDeviationDeg','1')
            field(state,'currentAngle','0')
        gun=state.find('gun')
        if gun is not None:
            gun_def=prop(name,'building/turretGunDef')
            field(gun,'def',gun_def)
            # Retain the nested identity allocated by build.py; the host's numeric
            # ID is already registered even when its Def prefix differs.
            field(gun,'id',gun_def+re.search(r'\d+$',gun.findtext('id')).group())
            verb=gun.find('verbTracker/verbs/li')
            verb.set('Class','DeltaV.Verb_SpaceTurretGround')
            field(verb,'loadID','CompEquippable_'+gun.findtext('id')+'_0')
    if name == 'DeltaV_ShieldGenerator':
        for obsolete in ('DeltaV_guardRecoveryTicksRemaining','DeltaV_guardUnlocked'):
            node=state.find(obsolete)
            if node is not None: state.remove(node)
        field(state,'currentHitPoints','-1')
        field(state,'DeltaV_shieldMode',r['stateOverrides'].get('DeltaV_shieldMode','Guard'))
        field(state,'DeltaV_regularCapacity',prop(name,"comps/li[@Class='DeltaV.CompProperties_SpaceShield']/regularCapacity",'750'))
        field(state,'DeltaV_autoRejoinPercent','10')
        field(state,'fuel',prop(name,"comps/li[@Class='CompProperties_Refuelable']/fuelCapacity"))
        field(state,'configuredTargetFuelLevel',prop(name,"comps/li[@Class='CompProperties_Refuelable']/fuelCapacity"))
        field(state,'DeltaV_shieldProjection',r['stateOverrides'].get('DeltaV_shieldProjection','32'))
        field(state,'DeltaV_shieldLength',r['stateOverrides'].get('DeltaV_shieldLength','32'))


def validate_and_draw(name, plan, records, foundation, roofs, reachable, here, generated):
    w,h=plan['size']; scale=19
    left,top= (550,170) if name=='ShieldTarget' else (35,35)
    img=Image.new('RGB',(w*scale+left+35,h*scale+top+35+(95 if name=='WeaponRange' else 75)),'#101822');d=ImageDraw.Draw(img)
    for x,z in foundation:
        d.rectangle((left+x*scale,top+(h-z-1)*scale,left+(x+1)*scale,top+(h-z)*scale),
                    fill='#e5bd43' if (x,z) in plan['surfaceDefs'] else '#354653',outline='#415563')
    paint_colors = {paint:color for _,paint,color in TARGET_BANDS}
    terminal_labels = {'DeltaV_RangeTerminal_'+preset: str(column)
                       for column,(_,presets) in enumerate(TERMINAL_COLUMNS,1) for preset in presets}
    for r in records:
        if r['layer']=='conduit':continue
        xs,zs=zip(*r['cells']);box=(left+min(xs)*scale+1,top+(h-max(zs)-1)*scale+1,left+(max(xs)+1)*scale-1,top+(h-min(zs))*scale-1)
        color='#94adbe'
        if r['name'].startswith('DeltaV_Weapon_'):color='#d59758'
        elif 'Shield' in r['name']:color='#72a7e1'
        elif 'Terminal' in r['name']:color='#7ed29d'
        elif r['layer']=='attachment':color='#dfd17c'
        elif r['name'] in ('Wall','GravshipHull'):
            color=paint_colors.get(r['stateOverrides'].get('paintColorDef'),'#74868d')
        d.rectangle(box,fill=color)
        if r['name'] not in ('Wall','GravshipHull'):
            label=r['name'].replace('DeltaV_RangeTerminal_','').replace('DeltaV_Weapon_','').replace('DeltaV_','')[:3]
            label=terminal_labels.get(r['name'],label)
            if r['name'].endswith('MainMedium'):
                label=('S' if r['stateOverrides'].get('salvoSet')=='Secondary' else 'M')+r['stateOverrides']['groupNumber']
                d.text(((box[0]+box[2])//2,(box[1]+box[3])//2),label,anchor='mm',fill='#101822')
            else:
                if r['name']==MAGAZINE:
                    label='HE' if r['stateOverrides']['_selectedHead']==STEEL_HEAD else 'AP'
                elif r['name']=='DeltaV_Building_AutoAimPluginII': label='Aim'
                elif r['name']==RANGE_RAIL: label='S4'
                elif name=='ShieldTarget' and r['name']=='DeltaV_ShieldGenerator':
                    label='G'+r['stateOverrides']['DeltaV_shieldGroundRadius']
                d.text((box[0]+1,box[1]+1),label,fill='#101822')
        if r['hasInteraction']:
            ix,_,iz=r['interaction'];dx,dz=[(ix,iz),(iz,-ix),(-ix,-iz),(-iz,ix)][r['rotation']]
            p=(r['root'][0]+dx,r['root'][1]+dz)
            assert p in reachable,(r['name'],'inaccessible station')
        if name=='ShieldTarget' and r['stateOverrides'].get('_rangeLine'):
            px,pz=(min(xs)+max(xs)+1)/2,(min(zs)+max(zs)+1)/2
            distance=float(r['stateOverrides']['DeltaV_shieldProjection'])
            half=float(r['stateOverrides']['DeltaV_shieldLength'])/2
            pixel=lambda x,z:(left+x*scale,top+(h-z)*scale)
            degrees=int(r['stateOverrides']['DeltaV_shieldAngle'])
            angle=math.radians(180+degrees)
            nx,nz=math.cos(angle),math.sin(angle)
            cx,cz=px+nx*distance,pz+nz*distance
            color='#dfd17c' if degrees else '#72a7e1'
            d.line((pixel(cx-nz*half,cz+nx*half),pixel(cx+nz*half,cz-nx*half)),fill=color,width=3)
    if name=='WeaponRange':
        batteries=[r for r in records if r['name']=='Battery']
        assert len(batteries)==60 and all(r['rotation']==1 and r['root'][1]<9 for r in batteries)
        assert sum(r['name'].startswith('DeltaV_RangeTerminal_') for r in records)==12
        rail=[r for r in records if r['name'] in (RANGE_RAIL,'DeltaV_Weapon_RailgunAccelerator')]
        assert len(rail)==10
        assert {tuple(c) for r in rail for c in r['cells']}=={(x,z) for x in range(34,44) for z in range(21,24)}
        blocked={tuple(c) for r in records if r['name']=='DeltaV_RangeBlastDoor' or
                 (r['passability']=='Impassable' and r['name'] not in ('Door','DeltaV_DockingPort')) for c in r['cells']}
        seen={(1,2)}; queue=deque(seen)
        while queue:
            x,z=queue.popleft()
            for p in ((x-1,z),(x+1,z),(x,z-1),(x,z+1)):
                if p in foundation and p not in blocked and p not in seen:seen.add(p);queue.append(p)
        assert (4,3) in seen and all((x,TERMINAL_ROWS[0]-1) not in seen for x,_ in TERMINAL_COLUMNS)
        assert all(p in seen for p in plan['surfaceDefs'])
    else:
        assert sum(r['name']=='DeltaV_ShieldGenerator' for r in records)==3
        assert sum(r['name']=='Battery' and any(z==30 for x,z in r['cells']) for r in records)==5
    d.text((left,top+h*scale+12),name+' | North up | FIRE EAST > / TARGET FACES WEST <',fill='white')
    d.text((left,top+h*scale+32),'1: No shield | 2: Kinetic | 3: Electromagnetic | 4: Guard (single / joint)' if name=='WeaponRange'
           else 'West armour: painted witness bands | Blue: 0 deg shield | Yellow: 45 deg shield',fill='white')
    d.text((left,top+h*scale+52),'Live ammunition, finite energy and real damage. No automatic reset.',fill='white')
    if name=='WeaponRange':
        d.text((left,top+h*scale+72),'Kinetic: 0 deg / 35%, 45 deg / 7%, 45 deg / 35%, 45 deg / 100%',fill='white')
        d.text((left,top+h*scale+92),'Electromagnetic: 0 deg / 20%, 45 deg / 20%, 45 deg / 50%, 45 deg / 100%',fill='white')
        d.text((left,top+h*scale+112),'North row main: steel | South row secondary: uranium | East S4: railgun',fill='white')
    else:
        d.text((left,top+h*scale+72),'Joint guard: three share regular capacity. The fixed rail lane strikes G39 only.',fill='white')
    img.save(here/(name+'.png'))
